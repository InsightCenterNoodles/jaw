use std::collections::HashMap;

use anyhow::{Result, anyhow, bail};

use crate::compile::{BitWidth, Datatype, Primitive, Signedness, Type, TypeID, TypeKind, World};

use super::*;

pub fn emit(world: &World, out: &mut Outfile) -> Result<()> {
    let ctx = PythonContext::new(world)?;

    emit_preamble(out);
    out.newline();

    for (id, ty) in ctx.types() {
        emit_type_definition(&ctx, out, id, ty)?;
    }

    for (id, ty) in ctx.types() {
        emit_read_impl(&ctx, out, id, ty)?;
        emit_write_impl(&ctx, out, id, ty)?;
    }

    Ok(())
}

struct PythonContext<'a> {
    world: &'a World,
    names: HashMap<TypeID, String>,
}

impl<'a> PythonContext<'a> {
    fn new(world: &'a World) -> Result<Self> {
        let mut names = HashMap::new();
        for (id, ty) in world.iter() {
            names.insert(id, sanitize(ty.ident.to_string()));
        }
        Ok(Self { world, names })
    }

    fn name_of(&self, id: TypeID) -> String {
        self.names
            .get(&id)
            .expect("missing generated name for type id")
            .clone()
    }

    fn types(&'a self) -> impl Iterator<Item = (TypeID, &'a Type)> + 'a {
        self.world.iter()
    }

    fn resolve_alias(&self, id: TypeID) -> TypeID {
        let mut cur = id;
        loop {
            let ty = self.world.lookup(cur);
            match &ty.kind {
                TypeKind::Alias(a) => cur = a.other,
                _ => return cur,
            }
        }
    }

    fn is_void(&self, id: TypeID) -> bool {
        matches!(self.world.lookup(id).kind, TypeKind::Void)
    }

    fn direct_primitive(&self, id: TypeID) -> Option<Primitive> {
        let resolved = self.resolve_alias(id);
        match self.world.lookup(resolved).kind {
            TypeKind::Primitive(p) => Some(p),
            _ => None,
        }
    }

    fn underlying_primitive(&self, id: TypeID) -> Option<Primitive> {
        let ty = self.world.lookup(id);
        match &ty.kind {
            TypeKind::Primitive(p) => Some(*p),
            TypeKind::Alias(a) => self.underlying_primitive(a.other),
            TypeKind::Enum(e) => self.underlying_primitive(e.underlying),
            _ => None,
        }
    }

    fn type_hint(&self, id: TypeID) -> Result<String> {
        let ty = self.world.lookup(id);
        let hint = match &ty.kind {
            TypeKind::Primitive(p) => match p.dtype {
                Datatype::Float => "float".to_string(),
                Datatype::Integer => "int".to_string(),
            },
            TypeKind::Void => "None".into(),
            TypeKind::Alias(alias) => return self.type_hint(alias.other),
            TypeKind::Pack(_) | TypeKind::Enum(_) | TypeKind::Bitfld(_) => self.name_of(id),
            TypeKind::Variant(_) => self.name_of(id),
            TypeKind::Sequence(_) => self.name_of(id),
            TypeKind::DynamicArray(arr) => {
                if self.direct_primitive(arr.value_type).is_some() {
                    "array.array".into()
                } else {
                    "list".into()
                }
            }
            TypeKind::FixedArray(arr) => {
                if self.direct_primitive(arr.value_type).is_some() {
                    "array.array".into()
                } else {
                    "list".into()
                }
            }
        };
        Ok(hint)
    }
}

fn emit_preamble(out: &mut impl Sink) {
    out.wln("# Generated by jaw. Do not edit.");
    out.wln("from __future__ import annotations");
    out.wln("import array");
    out.wln("import enum");
    out.wln("import struct");
    out.wln("import sys");
    out.wln("from dataclasses import dataclass");
    out.wln("from typing import Iterable");
    out.newline();

    out.wln("class Reader:");
    {
        let mut idt = out.indent();
        idt.wln("def __init__(self, data):");
        {
            let mut body = idt.indent();
            body.wln("self._buf = memoryview(data)");
            body.wln("self._pos = 0");
        }
        idt.wln("def _read_prim(self, fmt):");
        {
            let mut body = idt.indent();
            body.wln("size = struct.calcsize(fmt)");
            body.wln("end = self._pos + size");
            body.wln("if end > len(self._buf): raise EOFError('not enough data')");
            body.wln("(value,) = struct.unpack_from(fmt, self._buf, self._pos)");
            body.wln("self._pos = end");
            body.wln("return value");
        }
        idt.wln("def read_bytes(self, n):");
        {
            let mut body = idt.indent();
            body.wln("n = int(n)");
            body.wln("start = self._pos");
            body.wln("end = start + n");
            body.wln("if end > len(self._buf): raise EOFError('not enough data')");
            body.wln("self._pos = end");
            body.wln("return self._buf[start:end]");
        }
        for (method, fmt) in [
            ("read_u8", "<B"),
            ("read_i8", "<b"),
            ("read_u16", "<H"),
            ("read_i16", "<h"),
            ("read_u32", "<I"),
            ("read_i32", "<i"),
            ("read_u64", "<Q"),
            ("read_i64", "<q"),
            ("read_f32", "<f"),
            ("read_f64", "<d"),
        ] {
            idt.wln(&format!("def {method}(self):"));
            let mut body = idt.indent();
            body.wln(&format!("return self._read_prim('{fmt}')"));
        }
    }
    out.newline();

    out.wln("class Writer:");
    {
        let mut idt = out.indent();
        idt.wln("def __init__(self):");
        {
            let mut body = idt.indent();
            body.wln("self._out = bytearray()");
        }
        idt.wln("def getvalue(self):");
        {
            let mut body = idt.indent();
            body.wln("return bytes(self._out)");
        }
        idt.wln("def write_bytes(self, b):");
        {
            let mut body = idt.indent();
            body.wln("self._out.extend(b)");
        }
        idt.wln("def _write_prim(self, fmt, value):");
        {
            let mut body = idt.indent();
            body.wln("self._out.extend(struct.pack(fmt, value))");
        }
        for (method, fmt) in [
            ("write_u8", "<B"),
            ("write_i8", "<b"),
            ("write_u16", "<H"),
            ("write_i16", "<h"),
            ("write_u32", "<I"),
            ("write_i32", "<i"),
            ("write_u64", "<Q"),
            ("write_i64", "<q"),
            ("write_f32", "<f"),
            ("write_f64", "<d"),
        ] {
            idt.wln(&format!("def {method}(self, value):"));
            let mut body = idt.indent();
            body.wln(&format!("self._write_prim('{fmt}', value)"));
        }
    }
    out.newline();

    out.wln("def _read_primitive_array(reader, fmt, typecode, count):");
    {
        let mut idt = out.indent();
        idt.wln("count = int(count)");
        idt.wln("if count < 0: raise ValueError('negative array length')");
        idt.wln("size = struct.calcsize(fmt)");
        idt.wln("raw = reader.read_bytes(count * size)");
        idt.wln("arr = array.array(typecode)");
        idt.wln("arr.frombytes(raw)");
        idt.wln("if sys.byteorder != 'little' and arr.itemsize > 1: arr.byteswap()");
        idt.wln("return arr");
    }
    out.newline();
    out.wln("def _write_primitive_array(writer, fmt, typecode, values: Iterable):");
    {
        let mut idt = out.indent();
        idt.wln("if isinstance(values, array.array) and values.typecode == typecode:");
        {
            let mut body = idt.indent();
            body.wln("arr = values");
        }
        idt.wln("else:");
        {
            let mut body = idt.indent();
            body.wln("arr = array.array(typecode, values)");
        }
        idt.wln("if sys.byteorder != 'little' and arr.itemsize > 1:");
        {
            let mut body = idt.indent();
            body.wln("arr = arr[:]");
            body.wln("arr.byteswap()");
        }
        idt.wln("writer.write_bytes(arr.tobytes())");
    }
}

fn emit_type_definition(
    ctx: &PythonContext,
    out: &mut impl Sink,
    id: TypeID,
    ty: &Type,
) -> Result<()> {
    let name = ctx.name_of(id);
    match &ty.kind {
        TypeKind::Alias(alias) => {
            let target_hint = ctx.type_hint(alias.other)?;
            out.wln(&format!("{name} = {target_hint}"));
            out.newline();
        }
        TypeKind::Enum(enm) => {
            out.wln("@enum.unique");
            out.wln(&format!("class {name}(enum.IntEnum):"));
            {
                let mut idt = out.indent();
                for m in &enm.members {
                    idt.wln(&format!("{} = {}", sanitize(&m.name), m.value));
                }
                if let Some(default) = &enm.default {
                    idt.wln(&format!("{} = {}", sanitize(&default.name), default.value));
                    idt.wln(&format!("__default__ = {}", sanitize(&default.name)));
                }
            }
            out.newline();
        }
        TypeKind::Bitfld(bitfld) => {
            out.wln("@dataclass");
            out.wln(&format!("class {name}:"));
            {
                let mut idt = out.indent();
                for m in &bitfld.members {
                    let hint = ctx.type_hint(m.underlying)?;
                    idt.wln(&format!("{}: {}", sanitize(&m.name), hint));
                }
            }
            out.newline();
        }
        TypeKind::Pack(pack) => {
            out.wln("@dataclass");
            out.wln(&format!("class {name}:"));
            {
                let mut idt = out.indent();
                for m in &pack.members {
                    let hint = ctx.type_hint(m.ty)?;
                    idt.wln(&format!("{}: {}", sanitize(&m.name), hint));
                }
            }
            out.newline();
        }
        TypeKind::Sequence(seq) => {
            out.wln("@dataclass");
            out.wln(&format!("class {name}:"));
            {
                let mut idt = out.indent();
                for m in &seq.members {
                    let hint = ctx.type_hint(m.ty)?;
                    idt.wln(&format!("{}: {} | None = None", sanitize(&m.name), hint));
                }
            }
            out.newline();
        }
        TypeKind::Variant(v) => {
            out.wln("@dataclass");
            out.wln(&format!("class {name}:"));
            {
                let mut idt = out.indent();
                idt.wln("tag: int = 0");
                idt.wln("value: object | None = None");

                for m in &v.members {
                    let mem_type_name = ctx.name_of(m.ty);
                    idt.wln("@staticmethod");

                    if ctx.is_void(m.ty) {
                        idt.wln(&format!("def make_{0}():", mem_type_name));
                    } else {
                        idt.wln(&format!("def make_{0}(value: {0}):", mem_type_name));
                    }

                    {
                        let mut idt = idt.indent();
                        idt.wln(&format!("ret = {name}()"));
                        idt.wln(&format!("ret.tag = {}", m.value));
                        if !ctx.is_void(m.ty) {
                            idt.wln(&format!("ret.value = value"));
                        }
                        idt.wln(&format!("return ret"));
                    }
                }
            }
            out.newline();
        }
        TypeKind::DynamicArray(_) | TypeKind::FixedArray(_) => {
            // Arrays are represented with built-in containers; no class emitted.
        }
        TypeKind::Primitive(_) | TypeKind::Void => {}
    }

    Ok(())
}

fn emit_read_impl(ctx: &PythonContext, out: &mut impl Sink, id: TypeID, ty: &Type) -> Result<()> {
    let name = ctx.name_of(id);
    match &ty.kind {
        TypeKind::Alias(alias) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            idt.wln(&format!(
                "return {}",
                read_expr(ctx, alias.other, "reader")?
            ));
            idt.newline();
        }
        TypeKind::Pack(pack) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            idt.wln(&format!("return {name}("));
            {
                let mut args = idt.indent();
                for m in &pack.members {
                    let expr = read_expr(ctx, m.ty, "reader")?;
                    args.wln(&format!("{} = {},", sanitize(&m.name), expr));
                }
            }
            idt.wln(")");
            idt.newline();
        }
        TypeKind::Enum(enm) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            let base_read = read_primitive_method(ctx, enm.underlying)?;
            idt.wln(&format!("raw = reader.{base_read}()"));
            idt.wln(&format!("if raw in {name}._value2member_map_:"));
            {
                let mut body = idt.indent();
                body.wln(&format!("return {name}(raw)"));
            }
            if let Some(default) = &enm.default {
                idt.wln(&format!("return {name}.{}", sanitize(&default.name)));
            } else {
                idt.wln(&format!(
                    "raise ValueError(f'invalid discriminant for {name}: {{raw!r}}')"
                ));
            }
            idt.newline();
        }
        TypeKind::Bitfld(bitfld) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            let base_read = read_primitive_method(ctx, bitfld.underlying)?;
            idt.wln(&format!("raw = reader.{base_read}()"));
            idt.wln(&format!("return {name}("));
            {
                let mut args = idt.indent();
                for m in &bitfld.members {
                    let start = m.range.start();
                    let end = m.range.end();
                    let width = end - start + 1;
                    let mask = (1u128 << width) - 1;
                    args.wln(&format!(
                        "{} = (raw >> {}) & 0x{:X},",
                        sanitize(&m.name),
                        start,
                        mask
                    ));
                }
            }
            idt.wln(")");
            idt.newline();
        }
        TypeKind::Variant(variant) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            let disc_read = read_primitive_method(ctx, variant.discriminant)?;
            idt.wln(&format!("tag = reader.{disc_read}()"));
            for m in &variant.members {
                idt.wln(&format!("if tag == {}:", m.value));
                let mut body = idt.indent();
                if ctx.is_void(m.ty) {
                    body.wln(&format!("return {name}(tag=tag, value=None)"));
                } else {
                    let expr = read_expr(ctx, m.ty, "reader")?;
                    body.wln(&format!("val = {expr}"));
                    body.wln(&format!("return {name}(tag=tag, value=val)"));
                }
            }
            idt.wln(&format!(
                "raise ValueError(f'unknown tag for {name}: {{tag!r}}')"
            ));
            idt.newline();
        }
        TypeKind::Sequence(seq) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            idt.wln(&format!("return {name}("));
            {
                let mut args = idt.indent();
                for m in &seq.members {
                    let expr = read_expr(ctx, m.ty, "reader")?;
                    args.wln(&format!("{} = {},", sanitize(&m.name), expr));
                }
            }
            idt.wln(")");
            idt.newline();
        }
        TypeKind::DynamicArray(arr) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            let size_read = read_primitive_method(ctx, arr.size_type)?;
            idt.wln(&format!("count = reader.{size_read}()"));
            if let Some(p) = ctx.direct_primitive(arr.value_type) {
                let fmt = map_primitive_fmt(p)?;
                let typecode = map_typecode(p)?;
                idt.wln(&format!(
                    "return _read_primitive_array(reader, '{fmt}', '{typecode}', count)"
                ));
            } else {
                idt.wln("out = []");
                idt.wln("for _ in range(int(count)):");
                let mut body = idt.indent();
                {
                    let expr = read_expr(ctx, arr.value_type, "reader")?;
                    body.wln(&format!("out.append({expr})"));
                    body.wln("return out");
                }
            }
            idt.newline();
        }
        TypeKind::FixedArray(arr) => {
            out.wln(&format!("def read_{name}(reader):"));
            let mut idt = out.indent();
            if let Some(p) = ctx.direct_primitive(arr.value_type) {
                let fmt = map_primitive_fmt(p)?;
                let typecode = map_typecode(p)?;
                idt.wln(&format!(
                    "return _read_primitive_array(reader, '{fmt}', '{typecode}', {})",
                    arr.count
                ));
            } else {
                idt.wln("out = []");
                idt.wln(&format!("for _ in range({}):", arr.count));
                let mut body = idt.indent();
                {
                    let expr = read_expr(ctx, arr.value_type, "reader")?;
                    body.wln(&format!("out.append({expr})"));
                    body.wln("return out");
                }
            }
            idt.newline();
        }
        TypeKind::Primitive(_) | TypeKind::Void => {}
    }

    Ok(())
}

fn emit_write_impl(ctx: &PythonContext, out: &mut impl Sink, id: TypeID, ty: &Type) -> Result<()> {
    let name = ctx.name_of(id);
    match &ty.kind {
        TypeKind::Alias(alias) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            write_value(ctx, &mut idt, alias.other, "value")?;
            idt.newline();
        }
        TypeKind::Pack(pack) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            for m in &pack.members {
                write_value(ctx, &mut idt, m.ty, &format!("value.{}", sanitize(&m.name)))?;
            }
            idt.newline();
        }
        TypeKind::Enum(enm) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            let write_fn = write_primitive_method(ctx, enm.underlying)?;
            idt.wln(&format!("writer.{write_fn}(int(value))"));
            idt.newline();
        }
        TypeKind::Bitfld(bitfld) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            let write_fn = write_primitive_method(ctx, bitfld.underlying)?;
            idt.wln("raw = 0");
            for m in &bitfld.members {
                let start = m.range.start();
                let end = m.range.end();
                let width = end - start + 1;
                let mask = (1u128 << width) - 1;
                idt.wln(&format!(
                    "raw |= (int(value.{}) & 0x{:X}) << {}",
                    sanitize(&m.name),
                    mask,
                    start
                ));
            }
            idt.wln(&format!("writer.{write_fn}(raw)"));
            idt.newline();
        }
        TypeKind::Variant(variant) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            let write_tag = write_primitive_method(ctx, variant.discriminant)?;
            idt.wln(&format!("writer.{write_tag}(int(value.tag))"));
            for m in &variant.members {
                idt.wln(&format!("if int(value.tag) == {}:", m.value));
                let mut body = idt.indent();
                if ctx.is_void(m.ty) {
                    body.wln("return");
                } else {
                    write_value(ctx, &mut body, m.ty, "value.value")?;
                    body.wln("return");
                }
            }
            idt.wln(&format!(
                "raise ValueError(f'unknown tag for {name}: {{value.tag!r}}')"
            ));
            idt.newline();
        }
        TypeKind::Sequence(seq) => {
            out.wln(&format!("def write_{name}(writer, value):"));
            let mut idt = out.indent();
            for m in &seq.members {
                write_value(ctx, &mut idt, m.ty, &format!("value.{}", sanitize(&m.name)))?;
            }
            idt.newline();
        }
        TypeKind::DynamicArray(arr) => {
            out.wln(&format!("def write_{name}(writer, values):"));
            let mut idt = out.indent();
            let size_write = write_primitive_method(ctx, arr.size_type)?;
            idt.wln(&format!("writer.{size_write}(len(values))"));
            if let Some(p) = ctx.direct_primitive(arr.value_type) {
                let fmt = map_primitive_fmt(p)?;
                let typecode = map_typecode(p)?;
                idt.wln(&format!(
                    "_write_primitive_array(writer, '{fmt}', '{typecode}', values)"
                ));
            } else {
                idt.wln("for item in values:");
                let mut body = idt.indent();
                write_value(ctx, &mut body, arr.value_type, "item")?;
            }
            idt.newline();
        }
        TypeKind::FixedArray(arr) => {
            out.wln(&format!("def write_{name}(writer, values):"));
            let mut idt = out.indent();
            if let Some(p) = ctx.direct_primitive(arr.value_type) {
                let fmt = map_primitive_fmt(p)?;
                let typecode = map_typecode(p)?;
                idt.wln(&format!(
                    "if len(values) != {}: raise ValueError('expected {} items')",
                    arr.count, arr.count
                ));
                idt.wln(&format!(
                    "_write_primitive_array(writer, '{fmt}', '{typecode}', values)"
                ));
            } else {
                idt.wln(&format!(
                    "if len(values) != {}: raise ValueError('expected {} items')",
                    arr.count, arr.count
                ));
                idt.wln("for item in values:");
                let mut body = idt.indent();
                write_value(ctx, &mut body, arr.value_type, "item")?;
            }
            idt.newline();
        }
        TypeKind::Primitive(_) | TypeKind::Void => {}
    }
    Ok(())
}

fn read_expr(ctx: &PythonContext, id: TypeID, reader_ident: &str) -> Result<String> {
    let ty = ctx.world.lookup(id);
    let expr = match &ty.kind {
        TypeKind::Primitive(p) => {
            let method = read_primitive_method_direct(*p)?;
            format!("{reader_ident}.{method}()")
        }
        TypeKind::Void => "None".into(),
        TypeKind::Alias(alias) => return read_expr(ctx, alias.other, reader_ident),
        _ => format!("read_{}({reader_ident})", ctx.name_of(id)),
    };
    Ok(expr)
}

fn write_value(
    ctx: &PythonContext,
    out: &mut impl Sink,
    id: TypeID,
    value_expr: &str,
) -> Result<()> {
    let ty = ctx.world.lookup(id);
    match &ty.kind {
        TypeKind::Primitive(p) => {
            let method = write_primitive_method_direct(*p)?;
            out.wln(&format!("writer.{method}({})", value_expr));
        }
        TypeKind::Void => {
            // nothing to write
        }
        TypeKind::Alias(alias) => write_value(ctx, out, alias.other, value_expr)?,
        _ => {
            out.wln(&format!(
                "write_{}(writer, {})",
                ctx.name_of(id),
                value_expr
            ));
        }
    }
    Ok(())
}

fn read_primitive_method(ctx: &PythonContext, id: TypeID) -> Result<&'static str> {
    let p = ctx
        .underlying_primitive(id)
        .ok_or_else(|| anyhow!("expected primitive-compatible type"))?;
    read_primitive_method_direct(p)
}

fn write_primitive_method(ctx: &PythonContext, id: TypeID) -> Result<&'static str> {
    let p = ctx
        .underlying_primitive(id)
        .ok_or_else(|| anyhow!("expected primitive-compatible type"))?;
    write_primitive_method_direct(p)
}

fn read_primitive_method_direct(p: Primitive) -> Result<&'static str> {
    match (p.dtype, p.sign, p.width) {
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W8) => Ok("read_u8"),
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W16) => Ok("read_u16"),
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W32) => Ok("read_u32"),
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W64) => Ok("read_u64"),
        (Datatype::Integer, Signedness::Signed, BitWidth::W8) => Ok("read_i8"),
        (Datatype::Integer, Signedness::Signed, BitWidth::W16) => Ok("read_i16"),
        (Datatype::Integer, Signedness::Signed, BitWidth::W32) => Ok("read_i32"),
        (Datatype::Integer, Signedness::Signed, BitWidth::W64) => Ok("read_i64"),
        (Datatype::Float, _, BitWidth::W32) => Ok("read_f32"),
        (Datatype::Float, _, BitWidth::W64) => Ok("read_f64"),
        _ => bail!("unsupported primitive type"),
    }
}

