fn sanitize_member(value: &str) -> String {
    let mut value = sanitize(value);
    if matches!(
        value.as_str(),
        "constructor" | "read" | "write" | "encode" | "decode"
    ) {
        value.push('_');
    }
    value
}

fn sanitize_static_member(value: &str) -> String {
    let mut value = sanitize_member(value);
    if matches!(
        value.as_str(),
        "name" | "length" | "prototype" | "caller" | "arguments"
    ) {
        value.push('_');
    }
    value
}

fn sanitize(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 1);
    for (index, ch) in value.chars().enumerate() {
        if (ch.is_ascii_alphanumeric() || ch == '_' || ch == '$')
            && !(index == 0 && ch.is_ascii_digit())
        {
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    if JS_KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

