fn emit_type(ctx: &SwiftContext, out: &mut impl Sink, id: TypeID, ty: &Type) -> Result<()> {
    match &ty.kind {
        TypeKind::Pack(value) => emit_struct(ctx, out, id, &value.members, value),
        TypeKind::Sequence(value) => emit_sequence(ctx, out, id, value),
        TypeKind::Enum(value) => emit_enum(ctx, out, id, value),
        TypeKind::Bitfld(value) => emit_bitfield(ctx, out, id, value),
        TypeKind::Variant(value) => emit_variant(ctx, out, id, value),
        TypeKind::DynamicArray(value) => emit_dynamic_array(ctx, out, id, value),
        TypeKind::FixedArray(value) => emit_fixed_array(ctx, out, id, value),
        TypeKind::Const(value) => emit_const(ctx, out, id, value),
        TypeKind::Bool | TypeKind::Primitive(_) | TypeKind::Void => Ok(()),
    }
}

fn emit_struct(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    members: &[crate::compile::StructMember],
    _pack: &Pack,
) -> Result<()> {
    emit_record(ctx, out, id, members, true)
}

fn emit_sequence(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    sequence: &Sequence,
) -> Result<()> {
    emit_record(ctx, out, id, &sequence.members, false)
}

fn emit_record(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    members: &[crate::compile::StructMember],
    fuse_fixed_io: bool,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let fixed_size = swift_fixed_size(ctx, id)?;
    let fixed_conformance = if fixed_size.is_some() {
        ", JawFixedSize"
    } else {
        ""
    };
    out.wln(&format!(
        "public struct {name}: Equatable, Sendable, JawReadable, JawWritable{fixed_conformance}"
    ));
    {
        let mut body = out.indent();
        if let Some(size) = fixed_size {
            body.wln(&format!("public static let jawEncodedSize = {size}"));
            body.newline();
        }
        for member in members {
            body.wln(&format!(
                "public var {}: {}",
                sanitize(&member.name),
                ctx.type_name(member.ty)
            ));
        }
        body.newline();
        let params = members
            .iter()
            .map(|m| format!("{}: {}", sanitize(&m.name), ctx.type_name(m.ty)))
            .collect::<Vec<_>>()
            .join(", ");
        body.wln(&format!("public init({params})"));
        {
            let mut init = body.indent();
            for member in members {
                let field = sanitize(&member.name);
                init.wln(&format!("self.{field} = {field}"));
            }
        }
        body.newline();
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut read = body.indent();
            if fuse_fixed_io {
                read.wln("return try withUnsafeTemporaryAllocation(byteCount: Self.jawEncodedSize, alignment: 1)");
                {
                    let mut block = read.indent();
                    block.wln("buffer in");
                    block.wln("try input.jawRead(into: buffer)");
                    block.wln(
                        "var blockInput = JawFixedBufferReader(UnsafeRawBufferPointer(buffer))",
                    );
                    emit_record_read_body(ctx, &mut block, members, "blockInput");
                }
            } else {
                emit_record_read_body(ctx, &mut read, members, "input");
            }
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut write = body.indent();
            if fuse_fixed_io {
                write.wln("try withUnsafeTemporaryAllocation(byteCount: Self.jawEncodedSize, alignment: 1)");
                {
                    let mut block = write.indent();
                    block.wln("buffer in");
                    block.wln("var blockOutput = JawFixedBufferWriter(buffer)");
                    for member in members {
                        block.wln(&format!(
                            "try self.{}.jawWrite(to: &blockOutput)",
                            sanitize(&member.name)
                        ));
                    }
                    block.wln("try output.jawWrite(UnsafeRawBufferPointer(buffer))");
                }
            } else {
                for member in members {
                    write.wln(&format!(
                        "try self.{}.jawWrite(to: &output)",
                        sanitize(&member.name)
                    ));
                }
            }
        }
    }
    out.newline();
    Ok(())
}

fn emit_record_read_body(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    members: &[crate::compile::StructMember],
    input: &str,
) {
    for member in members {
        let field = sanitize(&member.name);
        out.wln(&format!(
            "let {field} = try {}.jawRead(from: &{input})",
            ctx.type_name(member.ty)
        ));
    }
    let args = members
        .iter()
        .map(|member| {
            let field = sanitize(&member.name);
            format!("{field}: {field}")
        })
        .collect::<Vec<_>>()
        .join(", ");
    out.wln(&format!("return Self({args})"));
}

fn emit_enum(ctx: &SwiftContext, out: &mut impl Sink, id: TypeID, value: &Enum) -> Result<()> {
    let name = ctx.declared_name(id);
    let base = ctx.type_name(value.underlying);
    let fixed_size = swift_fixed_size(ctx, id)?.expect("enum must have a fixed wire size");
    out.wln(&format!(
        "public struct {name}: Equatable, Hashable, Sendable, JawReadable, JawWritable, JawFixedSize"
    ));
    {
        let mut body = out.indent();
        body.wln(&format!("public static let jawEncodedSize = {fixed_size}"));
        body.wln(&format!("public let rawValue: {base}"));
        body.wln(&format!(
            "public init(rawValue: {base}) {{ self.rawValue = rawValue }}"
        ));
        body.newline();
        body.wln(&format!(
            "public enum Value: {base}, CaseIterable, Sendable"
        ));
        {
            let mut cases = body.indent();
            for member in &value.members {
                cases.wln(&format!(
                    "case {} = {}",
                    sanitize(&member.name),
                    member.value
                ));
            }
        }
        body.newline();
        for member in &value.members {
            let member_name = sanitize(&member.name);
            body.wln(&format!(
                "public static let {member_name} = Self(rawValue: {})",
                member.value
            ));
        }
        body.newline();
        body.wln("public func value() throws -> Value");
        {
            let mut method = body.indent();
            method.wln("guard let value = Value(rawValue: rawValue) else");
            {
                let mut guard_body = method.indent();
                guard_body.wln(&format!(
                    "throw JawError.invalidData(\"invalid value for {name}: \\(rawValue)\")"
                ));
            }
            method.wln("return value");
        }
        body.newline();
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut method = body.indent();
            method.wln(&format!("Self(rawValue: try {base}.jawRead(from: &input))"));
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut method = body.indent();
            method.wln("try rawValue.jawWrite(to: &output)");
        }
    }
    out.newline();
    Ok(())
}

fn emit_bitfield(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    value: &Bitfld,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let base = primitive_name(
        ctx.underlying_primitive(value.underlying)
            .expect("verified bitfield base must be primitive"),
    );
    let fixed_size = swift_fixed_size(ctx, id)?.expect("bitfield must have a fixed wire size");
    out.wln(&format!(
        "public struct {name}: Equatable, Hashable, Sendable, JawReadable, JawWritable, JawFixedSize"
    ));
    {
        let mut body = out.indent();
        body.wln(&format!("public static let jawEncodedSize = {fixed_size}"));
        body.wln(&format!("public var rawValue: {base}"));
        body.wln(&format!(
            "public init(rawValue: {base} = 0) {{ self.rawValue = rawValue }}"
        ));
        body.newline();
        for member in &value.members {
            let field = sanitize(&member.name);
            let field_type = ctx.type_name(member.underlying);
            let start = member.range.start();
            let width = member.range.end() - member.range.start() + 1;
            let mask = (1u128 << width) - 1;
            body.wln(&format!("public var {field}: {field_type}"));
            {
                let mut property = body.indent();
                property.wln("get");
                {
                    let mut getter = property.indent();
                    if matches!(ctx.lookup(member.underlying).kind, TypeKind::Enum(_)) {
                        getter.wln(&format!(
                            "{field_type}(rawValue: {}(truncatingIfNeeded: (rawValue >> {start}) & 0x{mask:X}))",
                            enum_base_name(ctx, member.underlying)
                        ));
                    } else {
                        getter.wln(&format!(
                            "{field_type}(truncatingIfNeeded: (rawValue >> {start}) & 0x{mask:X})"
                        ));
                    }
                }
                property.wln("set");
                {
                    let mut setter = property.indent();
                    setter.wln(&format!("let mask: {base} = 0x{mask:X}"));
                    let source = if matches!(ctx.lookup(member.underlying).kind, TypeKind::Enum(_))
                    {
                        "newValue.rawValue"
                    } else {
                        "newValue"
                    };
                    setter.wln(&format!(
                        "let bits = {base}(truncatingIfNeeded: {source}) & mask"
                    ));
                    setter.wln(&format!(
                        "rawValue = (rawValue & ~(mask << {start})) | (bits << {start})"
                    ));
                }
            }
            body.newline();
        }
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut method = body.indent();
            method.wln(&format!("Self(rawValue: try {base}.jawRead(from: &input))"));
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut method = body.indent();
            method.wln("try rawValue.jawWrite(to: &output)");
        }
    }
    out.newline();
    Ok(())
}

fn emit_variant(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    value: &Variant,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let tag_type = ctx.type_name(value.discriminant);
    let fixed_size = swift_fixed_size(ctx, id)?;
    let fixed_conformance = if fixed_size.is_some() {
        ", JawFixedSize"
    } else {
        ""
    };
    out.wln(&format!(
        "public indirect enum {name}: Equatable, Sendable, JawReadable, JawWritable{fixed_conformance}"
    ));
    {
        let mut body = out.indent();
        if let Some(size) = fixed_size {
            body.wln(&format!("public static let jawEncodedSize = {size}"));
            body.newline();
        }
        for member in &value.members {
            let case_name = variant_case_name(ctx, member.ty, member.value);
            if matches!(ctx.lookup(member.ty).kind, TypeKind::Void) {
                body.wln(&format!("case {case_name}"));
            } else {
                body.wln(&format!("case {case_name}({})", ctx.type_name(member.ty)));
            }
        }
        body.newline();
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut method = body.indent();
            method.wln(&format!("let tag = try {tag_type}.jawRead(from: &input)"));
            method.wln("switch tag");
            {
                let mut switch = method.indent();
                for member in &value.members {
                    let case_name = variant_case_name(ctx, member.ty, member.value);
                    switch.wln(&format!("case {}:", member.value));
                    if matches!(ctx.lookup(member.ty).kind, TypeKind::Void) {
                        switch.wln(&format!("return .{case_name}"));
                    } else {
                        switch.wln(&format!(
                            "return .{case_name}(try {}.jawRead(from: &input))",
                            ctx.type_name(member.ty)
                        ));
                    }
                }
                switch.wln("default:");
                switch.wln(&format!(
                    "throw JawError.invalidData(\"unknown tag for {name}: \\(tag)\")"
                ));
            }
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut method = body.indent();
            method.wln("switch self");
            {
                let mut switch = method.indent();
                for member in &value.members {
                    let case_name = variant_case_name(ctx, member.ty, member.value);
                    let is_void = matches!(ctx.lookup(member.ty).kind, TypeKind::Void);
                    if is_void {
                        switch.wln(&format!("case .{case_name}:"));
                    } else {
                        switch.wln(&format!("case .{case_name}(let value):"));
                    }
                    switch.wln(&format!("let tag: {tag_type} = {}", member.value));
                    switch.wln("try tag.jawWrite(to: &output)");
                    if !is_void {
                        switch.wln("try value.jawWrite(to: &output)");
                    }
                }
            }
        }
    }
    out.newline();
    Ok(())
}

fn emit_dynamic_array(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    value: &DynamicArray,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let element = ctx.type_name(value.value_type);
    let storage = if ctx.uses_data(id) {
        "Foundation.Data".to_string()
    } else {
        format!("[{element}]")
    };
    let bulk_primitive = ctx.direct_primitive(value.value_type).is_some();
    let size_type = ctx.type_name(value.size_type);
    out.wln(&format!(
        "public struct {name}: Equatable, Sendable, JawReadable, JawWritable"
    ));
    {
        let mut body = out.indent();
        body.wln(&format!("public var values: {storage}"));
        body.wln(&format!(
            "public init(_ values: {storage}) {{ self.values = values }}"
        ));
        body.newline();
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut method = body.indent();
            method.wln(&format!(
                "let encodedCount = try {size_type}.jawRead(from: &input)"
            ));
            method.wln("guard let count = Int(exactly: encodedCount) else");
            {
                let mut guard = method.indent();
                guard.wln("throw JawError.invalidData(\"array length too large\")");
            }
            emit_array_guard(ctx, &mut method, "count", value.value_type, &element);
            if ctx.uses_data(id) {
                method.wln("return Self(try input.jawReadExactly(count))");
            } else if bulk_primitive {
                method.wln(&format!(
                    "let values: [{element}] = try input.jawReadContiguousArray(count: count, repeating: 0)"
                ));
                method.wln("return Self(values)");
            } else {
                method.wln(&format!("var values: [{element}] = []"));
                method.wln("values.reserveCapacity(count)");
                method.wln("for _ in 0..<count");
                {
                    let mut loop_body = method.indent();
                    loop_body.wln(&format!(
                        "values.append(try {element}.jawRead(from: &input))"
                    ));
                }
                method.wln("return Self(values)");
            }
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut method = body.indent();
            method.wln(&format!(
                "guard let count = {size_type}(exactly: values.count) else"
            ));
            {
                let mut guard = method.indent();
                guard.wln("throw JawError.invalidData(\"array length too large to encode\")");
            }
            method.wln("try count.jawWrite(to: &output)");
            if ctx.uses_data(id) {
                method.wln("try output.jawWriteAll(values)");
            } else if bulk_primitive {
                method.wln("try output.jawWriteContiguousArray(values)");
            } else {
                method.wln("for value in values");
                {
                    let mut loop_body = method.indent();
                    loop_body.wln("try value.jawWrite(to: &output)");
                }
            }
        }
    }
    out.newline();
    Ok(())
}

fn emit_fixed_array(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    value: &FixedArray,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let element = ctx.type_name(value.value_type);
    let bulk_primitive = ctx.direct_primitive(value.value_type).is_some();
    let fixed_size = swift_fixed_size(ctx, id)?.expect("fixed array must have a fixed wire size");
    out.wln(&format!(
        "public struct {name}: Equatable, Sendable, JawReadable, JawWritable, JawFixedSize"
    ));
    {
        let mut body = out.indent();
        body.wln(&format!("public static let jawEncodedSize = {fixed_size}"));
        body.wln(&format!("public static let count = {}", value.count));
        body.wln(&format!("public var values: [{element}]"));
        body.wln(&format!(
            "public init(_ values: [{element}]) {{ self.values = values }}"
        ));
        body.newline();
        body.wln(
            "public static func jawRead<Input: JawInput>(from input: inout Input) throws -> Self",
        );
        {
            let mut method = body.indent();
            if bulk_primitive {
                method.wln(&format!(
                    "let values: [{element}] = try input.jawReadContiguousArray(count: Self.count, repeating: 0)"
                ));
            } else {
                method.wln(&format!("var values: [{element}] = []"));
                method.wln("values.reserveCapacity(Self.count)");
                method.wln("for _ in 0..<Self.count");
                {
                    let mut loop_body = method.indent();
                    loop_body.wln(&format!(
                        "values.append(try {element}.jawRead(from: &input))"
                    ));
                }
            }
            method.wln("return Self(values)");
        }
        body.newline();
        body.wln("public func jawWrite<Output: JawOutput>(to output: inout Output) throws");
        {
            let mut method = body.indent();
            method.wln("guard values.count == Self.count else");
            {
                let mut guard = method.indent();
                guard.wln("throw JawError.invalidData(\"fixed array has incorrect length\")");
            }
            if bulk_primitive {
                method.wln("try output.jawWriteContiguousArray(values)");
            } else {
                method.wln("for value in values");
                {
                    let mut loop_body = method.indent();
                    loop_body.wln("try value.jawWrite(to: &output)");
                }
            }
        }
    }
    out.newline();
    Ok(())
}

fn emit_const(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    id: TypeID,
    value: &crate::compile::Const,
) -> Result<()> {
    let name = ctx.declared_name(id);
    let ty = ctx.type_name(value.ty);
    let literal = match value.value {
        PrimitiveLiteral::Boolean(v) => v.to_string(),
        PrimitiveLiteral::Integer(v) => v.to_string(),
        PrimitiveLiteral::Real(v) => format!("{v:?}"),
    };
    out.wln(&format!("public let {name}: {ty} = {literal}"));
    out.newline();
    Ok(())
}

fn swift_fixed_size(ctx: &SwiftContext, id: TypeID) -> Result<Option<usize>> {
    let Some(size) = ctx.fixed_wire_size(id) else {
        return Ok(None);
    };
    if size > i64::MAX as u64 {
        bail!(
            "type {} has a fixed wire size that cannot fit in Swift Int",
            ctx.lookup(id).ident
        );
    }
    Ok(Some(size as usize))
}

fn emit_array_guard(
    ctx: &SwiftContext,
    out: &mut impl Sink,
    count: &str,
    element_id: TypeID,
    element: &str,
) {
    let Some(limit) = ctx.options.guard_array_size else {
        return;
    };
    if let Some(size) = ctx.fixed_wire_size(element_id) {
        out.wln(&format!("let elementSize = {size}"));
    } else {
        out.wln(&format!(
            "let elementSize = max(1, MemoryLayout<{element}>.stride)"
        ));
    }
    out.wln(&format!(
        "let (byteCount, overflow) = {count}.multipliedReportingOverflow(by: elementSize)"
    ));
    out.wln(&format!("guard !overflow, byteCount <= {limit} else"));
    {
        let mut guard = out.indent();
        guard.wln("throw JawError.invalidData(\"array too large\")");
    }
}

fn enum_base_name(ctx: &SwiftContext, id: TypeID) -> String {
    let TypeKind::Enum(value) = &ctx.lookup(id).kind else {
        unreachable!("expected enum")
    };
    ctx.type_name(value.underlying)
}

fn variant_case_name(ctx: &SwiftContext, id: TypeID, value: u64) -> String {
    let name = ctx.type_name(id);
    let mut chars = name.chars();
    let first = chars.next().map(|c| c.to_ascii_lowercase()).unwrap_or('_');
    sanitize(format!("{first}{}_{value}", chars.as_str()))
}

fn primitive_name(value: Primitive) -> &'static str {
    match (value.dtype, value.sign, value.width) {
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W8) => "UInt8",
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W16) => "UInt16",
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W32) => "UInt32",
        (Datatype::Integer, Signedness::Unsigned, BitWidth::W64) => "UInt64",
        (Datatype::Integer, Signedness::Signed, BitWidth::W8) => "Int8",
        (Datatype::Integer, Signedness::Signed, BitWidth::W16) => "Int16",
        (Datatype::Integer, Signedness::Signed, BitWidth::W32) => "Int32",
        (Datatype::Integer, Signedness::Signed, BitWidth::W64) => "Int64",
        (Datatype::Float, _, BitWidth::W32) => "Float",
        (Datatype::Float, _, BitWidth::W64) => "Double",
        _ => unreachable!("unsupported verified primitive"),
    }
}

fn sanitize(value: impl AsRef<str>) -> String {
    let value = value.as_ref();
    let mut out = String::with_capacity(value.len() + 1);
    for (index, ch) in value.chars().enumerate() {
        if (ch.is_ascii_alphanumeric() || ch == '_') && !(index == 0 && ch.is_ascii_digit()) {
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    if SWIFT_KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

